func findTemplate(db *DB, key string) *Template {
	for _, t := range builtinTemplates {
		if t.Key == key {
			return t
		}
	}
	for _, t := range db.Templates {
		if t.Key == key {
			return t
		}
	}
	return nil
}

func stagesFromTemplate(t *Template) []*Stage {
	var out []*Stage
	for _, ts := range t.Stages {
		st := &Stage{ID: newID(), Name: ts.Name, Goal: ts.Goal, Guide: ts.Guide, Status: "todo", UpdatedAt: now(),
			Submissions: []Submission{}, Reviews: []Review{}}
		for _, c := range ts.Checklist {
			st.Checklist = append(st.Checklist, CheckItem{Text: c})
		}
		if st.Checklist == nil {
			st.Checklist = []CheckItem{}
		}
		out = append(out, st)
	}
	return out
}
